#!/usr/bin/env python3
"""Builds the installable web (PWA) version of QazoHisob.

    python3 tool/build_web.py [--base-href /path/]

Runs `flutter build web` with all resources served locally (no CDN), then
writes build/web/sw.js: a service worker that pre-caches the app so it keeps
working offline after the first visit.
"""
import argparse
import hashlib
import json
import pathlib
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / 'build' / 'web'

# Loaded on every start; cached at install time. Everything else that the
# app requests (other CanvasKit variants, fonts) is cached on first use.
PRECACHE_GLOBS = [
    'index.html', 'flutter.js', 'flutter_bootstrap.js', 'main.dart.js',
    'manifest.json', 'version.json', 'favicon.png', 'sqlite3.wasm',
    'drift_worker.js', 'icons/*', 'assets/**/*',
    'canvaskit/canvaskit.js', 'canvaskit/canvaskit.wasm',
]

SW_TEMPLATE = """// Generated by tool/build_web.py — do not edit.
const CACHE = 'qazohisob-%(version)s';
const PRECACHE = %(files)s;

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE)
      .then((cache) => cache.addAll(PRECACHE))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(
        keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  if (new URL(request.url).origin !== self.location.origin) return;

  // Pages: network first so updates arrive, cached copy when offline.
  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE).then((c) => c.put('index.html', copy));
          return response;
        })
        .catch(() => caches.match('index.html')),
    );
    return;
  }

  // Everything else: cache first, then network (and remember it).
  event.respondWith(
    caches.match(request, { ignoreSearch: true }).then((hit) => hit ||
      fetch(request).then((response) => {
        if (response.ok) {
          const copy = response.clone();
          caches.open(CACHE).then((c) => c.put(request, copy));
        }
        return response;
      })),
  );
});
"""


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        '--base-href', default=None,
        help='Fixed base path such as /app/. By default the build uses a '
             'relative base, so it works from any folder or domain.')
    args = parser.parse_args()

    subprocess.run(
        ['flutter', 'build', 'web', '--release', '--no-web-resources-cdn',
         '--no-wasm-dry-run', '--base-href', args.base_href or '/'],
        cwd=ROOT, check=True)

    if args.base_href is None:
        index = OUT / 'index.html'
        index.write_text(index.read_text().replace(
            '<base href="/">', '<base href="./">'))

    # Flutter's own (deprecated) service worker is replaced by sw.js.
    (OUT / 'flutter_service_worker.js').unlink(missing_ok=True)

    files = sorted({
        p.relative_to(OUT).as_posix()
        for pattern in PRECACHE_GLOBS
        for p in OUT.glob(pattern)
        if p.is_file()
    })
    digest = hashlib.sha256()
    for f in files:
        digest.update((OUT / f).read_bytes())
    (OUT / 'sw.js').write_text(SW_TEMPLATE % {
        'version': digest.hexdigest()[:12],
        'files': json.dumps(files, indent=2),
    })
    print(f'sw.js: {len(files)} files pre-cached, '
          f'version {digest.hexdigest()[:12]}')


if __name__ == '__main__':
    main()
